#!/usr/bin/env node
/**
 * Points clients/active/* at one client folder.
 *   CLIENT=demo-builder npm run build      (runs automatically before build/dev/test)
 *   node scripts/select-client.mjs demo-builder
 * Without CLIENT or an argument, the committed selection is left as it is.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const slug = process.argv[2] || process.env.CLIENT;
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
if (!slug) process.exit(0);
if (!/^[a-z0-9-]+$/.test(slug) || !existsSync(path.join(root, "clients", slug, "config.ts"))) {
  console.error(`[select-client] Unknown client "${slug}". Folders: clients/<slug>/config.ts`);
  process.exit(1);
}
const clientConfig = readFileSync(path.join(root, "clients", slug, "config.ts"), "utf8");
const pack = /pack:\s*"([a-z0-9-_]+)"/.exec(clientConfig)?.[1];
if (!pack || !existsSync(path.join(root, "packs", pack, "pack.ts"))) {
  console.error(`[select-client] clients/${slug}/config.ts names pack "${pack}", but packs/${pack}/pack.ts doesn't exist`);
  process.exit(1);
}
const dir = path.join(root, "clients", "active");
mkdirSync(dir, { recursive: true });
const head = `// Generated by scripts/select-client.mjs. Active client: ${slug}. Change with CLIENT=<slug>.\n`;
writeFileSync(path.join(dir, "config.ts"), `${head}export { config } from "../${slug}/config";\n`);
writeFileSync(path.join(dir, "content.ts"), `${head}export * from "../${slug}/content";\n`);
writeFileSync(path.join(dir, "brand.tsx"), `${head}export { Logo, faviconSvg } from "../${slug}/brand";\n`);
const pdir = path.join(root, "packs", "active");
mkdirSync(pdir, { recursive: true });
const phead = `// Generated by scripts/select-client.mjs. Active pack: ${pack} (from clients/${slug}/config.ts).\n`;
writeFileSync(path.join(pdir, "meta.ts"), `${phead}export { meta } from "../${pack}/meta";\n`);
writeFileSync(path.join(pdir, "pack.ts"), `${phead}export * from "../${pack}/pack";\n`);
writeFileSync(path.join(pdir, "content.ts"), `${phead}export * from "../${pack}/content";\n`);
writeFileSync(path.join(pdir, "form.ts"), `${phead}export * from "../${pack}/form/schema";\n`);
writeFileSync(path.join(pdir, "checklist.ts"), `${phead}export * from "../${pack}/checklist";\n`);
writeFileSync(path.join(pdir, "form-ui.tsx"), `${phead}export { PackStepFields } from "../${pack}/form/StepFields";\n`);
console.log(`[select-client] active client: ${slug}, pack: ${pack}`);
